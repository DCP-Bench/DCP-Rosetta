# four_numbers: a SCIP (Python) model from DCP Rosetta.
# Download the `four_numbers.json` instances from the model's page:
#   https://dcp-bench.github.io/DCP-Rosetta/problems/four_numbers.html
# Then run it on the first instance (after `pip install pyscipopt numpy`):
#   python four_numbers.py four_numbers.json

from itertools import combinations

from pyscipopt import Model, quicksum


def create_model(instance):
    """Find three integers, each from 1 to 10, such that every number in the
    instance is the sum of some nonempty subset of the three."""
    numbers = instance["numbers"]  # numbers[i]: a number the three integers must generate as a subset sum

    model = Model("four_numbers")

    # x[j] is the j-th of the three integers to find; the statement bounds each between 1 and 10 inclusive
    x = [model.addVar(f"x_{j}", vtype="I", lb=1, ub=10) for j in range(3)]

    # The nonempty subsets of the positions 0, 1, 2. The empty subset sums to 0, which no number from 1 to 10
    # can equal, so it is left out.
    subsets = [S for size in range(1, 4) for S in combinations(range(3), size)]

    # pick[i, s] is 1 when number i is the sum of the integers in subset s, and 0 when not
    pick = model.addMatrixVar((len(numbers), len(subsets)), vtype="B", name="pick")

    # Each number is generated by at least one subset.
    model.addMatrixCons(pick.sum(axis=1) >= 1)

    # When pick[i, s] is 1, the integers in subset s sum to number i. SCIP's indicator constraints take no
    # equality, so each equality is written as two indicators on the same binary, one for each side.
    for i, n in enumerate(numbers):
        for s, S in enumerate(subsets):
            total = quicksum(x[j] for j in S)
            model.addConsIndicator(total <= n, binvar=pick[i, s])
            model.addConsIndicator(total >= n, binvar=pick[i, s])

    return model, {"x": x}


if __name__ == "__main__":
    import json
    import sys
    import numpy as np

    instances = json.load(open(sys.argv[1]))
    index = 0 if len(sys.argv) <= 2 else int(sys.argv[2])

    model, outputs = create_model(instances[index])
    model.hideOutput()  # no solver log
    model.optimize()

    if model.getStatus() == "optimal":  # a proven optimum, or with no objective a solution
        value = np.vectorize(lambda var: round(model.getVal(var)))  # make it work on nested variables
        for name, output in outputs.items():
            print(name, "=", value(output))
    else:
        print("No solution:", model.getStatus())
